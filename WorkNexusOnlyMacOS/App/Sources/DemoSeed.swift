/// `WN_DEMO=1` (DEBUG builds only): the app runs on fake accounts and tickets, an in-memory (or `WN_DB_PATH`) database and
/// an in-memory credential store; every background job that would reach a server (sync, chat, notifications, update
/// checks, tray) stays off. For screenshots and UI checks — never for real use.
enum DemoMode {
    static var isEnabled: Bool {
        #if DEBUG
        ProcessInfo.processInfo.environment["WN_DEMO"] == "1"
        #else
        false
        #endif
    }
}

enum DemoSeed {
    static func insert(services: AppServices) async {
        let ws = "default"
        let accounts = [
            Account(id: "demo-zt", workspaceId: ws, providerType: .zentao, handle: "an.nguyen", baseUrl: "https://zentao.demo.invalid"),
            Account(id: "demo-gl", workspaceId: ws, providerType: .gitlab, handle: "annguyen", baseUrl: "https://gitlab.demo.invalid"),
            Account(id: "demo-gh", workspaceId: ws, providerType: .github, handle: "an-nguyen", baseUrl: "https://api.github.com"),
        ]
        for a in accounts { _ = await services.workspaces.upsertAccount(a) }
        let now = Date()
        func t(_ n: Int, _ acc: String, _ type: ProviderType, _ kind: String, _ title: String, _ status: UnifiedStatus, _ p: Priority) -> Ticket {
            Ticket(id: "\(acc)-\(kind)-\(n)", accountId: acc, projectId: "\(acc)-p1", providerType: type, externalKey: "\(n)",
                   title: title, body: "Demo \(kind) generated by WN_DEMO.", priority: p, status: status, providerStatus: status.rawValue,
                   sourceHash: "h\(n)", externalType: kind, labels: n % 2 == 0 ? ["demo"] : [], assignee: "an.nguyen",
                   url: "https://zentao.demo.invalid/\(kind)-view-\(n).html", createdAt: now.addingTimeInterval(-Double(n) * 86_400),
                   updatedAt: now.addingTimeInterval(-Double(n) * 3_600))
        }
        let tickets = [
            t(1, "demo-zt", .zentao, "task", "Design the sign-in screen", .inprogress, .high),
            t(2, "demo-zt", .zentao, "task", "Wire the payment gateway", .todo, .urgent),
            t(3, "demo-zt", .zentao, "bug", "Crash when opening an empty project", .todo, .urgent),
            t(4, "demo-zt", .zentao, "bug", "Wrong total in the weekly report", .review, .medium),
            t(5, "demo-gl", .gitlab, "mergeRequest", "Refactor the sync coordinator", .review, .medium),
            t(6, "demo-gl", .gitlab, "issue", "Document the release process", .todo, .low),
            t(7, "demo-gh", .github, "pullRequest", "Bump dependencies", .inprogress, .low),
        ]
        _ = await services.tickets.upsertTickets(tickets)
    }
}

extension DemoSeed {
    /// Initial place for screenshots: `WN_DEMO_NAV` = `workspace[:section]`, `account:<id>[:<section>]`, `settings[:section]`, `chat`,
    /// `editor:<bug|task>`, `ticket:<id>`, `connect`; `WN_DEMO_THEME` = `light|dark|midnight`.
    @MainActor
    static func applyEnvironment(shell: ShellModel) {
        let env = ProcessInfo.processInfo.environment
        if let t = env["WN_DEMO_THEME"], let v = ThemeVariant(rawValue: t) { shell.updateSettings { $0.variant = v } }
        if let size = env["WN_DEMO_SIZE"]?.split(separator: "x").compactMap({ Double($0) }), size.count == 2 {
            Task { @MainActor in
                try? await Task.sleep(for: .seconds(1))
                NSApp.windows.first(where: { $0.canBecomeMain })?.setContentSize(NSSize(width: size[0], height: size[1]))
            }
        }
        guard let spec = env["WN_DEMO_NAV"] else { return }
        let p = spec.split(separator: ":").map(String.init)
        switch p.first {
        case "workspace": shell.nav.select(.workspace); if p.count > 1 { shell.nav.setWorkspaceSection(p[1]) }
        case "settings": shell.nav.select(.settings); if p.count > 1 { shell.nav.setSettingsSection(p[1]) }
        case "chat": shell.nav.select(.chat)
        case "account" where p.count > 1:
            shell.nav.select(.account(p[1]))
            if p.count > 2 { shell.nav.setSection(SectionID(p[2]), accountId: p[1]) }
        case "editor": shell.nav.select(.workspace); shell.nav.openEditor(p.count > 1 && p[1] == "task" ? .newTask(accountId: "demo-zt") : .newBug(accountId: "demo-zt"))
        // A ticket id holds colons of its own (`account:task:12`): everything after "ticket:" is the id.
        case "ticket" where p.count > 1: shell.nav.select(.workspace); shell.nav.openTicket(p[1...].joined(separator: ":"))
        case "connect": shell.connectRequested = true
        case "quicksettings": shell.quickSettingsOpen = true
        default: break
        }
    }
}
